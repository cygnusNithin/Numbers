// PART H — ARITHMETIC GAPS
// ═══════════════════════════════════════════════════════════════
function testArithmeticGaps(trainCycles) {
  // For each day, sort new numbers and look for arithmetic patterns
  const cycle = trainCycles.find((c) => c.cycleNumber === 4);
  if (!cycle) return;

  let totalArithDays=0, totalDays=0;

  for (const dayEntry of cycle.drawEntries.slice(0,30)) {
    const newNums = dayEntry.numbers
      .filter((n)=>n.isNew)
      .map((n)=>numVal(n.number))
      .sort((a,b)=>a-b);

    if (newNums.length < 10) continue;
    totalDays++;

    const diffs = newNums.slice(1).map((v,i) => v-newNums[i]);
    const uniqueDiffs = [...new Set(diffs)];

    // Is it arithmetic? (all same diff)
    if (uniqueDiffs.length === 1) {
      totalArithDays++;
      console.log(`  Day ${dayEntry.dayIndexInCycle}: ARITHMETIC sequence! step=${uniqueDiffs[0]}, n=${newNums.length}`);
      continue;
    }

    // Top 3 most common gaps
    const gapFreq = {};
    diffs.forEach((d) => { gapFreq[d]=(gapFreq[d]||0)+1; });
    const topGaps = Object.entries(gapFreq).sort((a,b)=>b[1]-a[1]).slice(0,3);
    const topGapCount = topGaps.reduce((a,[,v])=>a+v,0);
    const topGapPct   = (topGapCount/diffs.length*100).toFixed(0);

    // Is there a dominant gap?
    if (parseFloat(topGaps[0]?.[1]||0)/diffs.length > 0.5) {
      console.log(`  Day ${dayEntry.dayIndexInCycle}: dominant gap=${topGaps[0][0]} (${(topGaps[0][1]/diffs.length*100).toFixed(0)}%), n=${newNums.length}`);
    }
  }

  if (totalArithDays === 0) {
    console.log(`\n  No arithmetic sequences found in daily draws.`);
    console.log(`  → Numbers are not drawn in arithmetic progressions.`);
  } else {
    console.log(`\n  Arithmetic days: ${totalArithDays}/${totalDays}`);
  }
}

