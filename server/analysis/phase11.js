// PART I — CROSS-CYCLE RANK FORMULA
// ═══════════════════════════════════════════════════════════════
function testCrossCycleRankFormula(trainCycles) {
  const c2 = trainCycles.find((c) => c.cycleNumber === 2);
  const c3 = trainCycles.find((c) => c.cycleNumber === 3);
  const c4 = trainCycles.find((c) => c.cycleNumber === 4);
  if (!c2||!c3||!c4) return;

  // Build rank maps (rank = position in unique sequence 1..10000)
  const buildRankMap = (cycle) => {
    const seq = buildCycleSequence(cycle);
    const map = new Map();
    seq.forEach((entry, i) => map.set(entry.number, i+1));
    return map;
  };

  const rank2 = buildRankMap(c2);
  const rank3 = buildRankMap(c3);
  const rank4 = buildRankMap(c4);

  // Get all numbers present in all 3 cycles
  const common = [...rank2.keys()].filter((n) => rank3.has(n) && rank4.has(n));

  console.log(`\n  Cross-cycle rank analysis (${common.length} numbers):`);

  // Test: rank3 = f(rank2)?
  // Simple: rank3 = 10001 - rank2 (reverse ordering)
  let reverseMatches = 0;
  const TOL = 500; // tolerance in rank units

  for (const num of common.slice(0, 1000)) {
    const r2 = rank2.get(num);
    const r3 = rank3.get(num);
    const predictedR3 = 10001 - r2;
    if (Math.abs(predictedR3 - r3) < TOL) reverseMatches++;
  }
  console.log(`  Reverse formula (rank3 = 10001-rank2): ${reverseMatches}/1000 within ±${TOL}`);

  // Test: rank4 = f(rank3)?
  let reverseMatches2 = 0;
  for (const num of common.slice(0, 1000)) {
    const r3 = rank3.get(num);
    const r4 = rank4.get(num);
    const predictedR4 = 10001 - r3;
    if (Math.abs(predictedR4 - r4) < TOL) reverseMatches2++;
  }
  console.log(`  Reverse formula (rank4 = 10001-rank3): ${reverseMatches2}/1000 within ±${TOL}`);

  // Test: shift formula
  for (const shift of [0, 1000, 2000, 3000, 5000]) {
    let matches = 0;
    for (const num of common.slice(0, 200)) {
      const r2 = rank2.get(num);
      const r4 = rank4.get(num);
      if (Math.abs(((r2+shift-1)%10000)+1 - r4) < TOL) matches++;
    }
    if (matches > 20) console.log(`  Shift formula (rank4=(rank2+${shift})%10000): ${matches}/200`);
  }

  // Show actual rank comparison for first 20 numbers
  console.log(`\n  First 20 numbers by C2 rank:`);
  console.log(`  Number | Rank_C2 | Rank_C3 | Rank_C4 | C3-C2 | C4-C3`);
  console.log(`  ` + "-".repeat(58));
  const first20 = [...rank2.entries()].sort((a,b)=>a[1]-b[1]).slice(0,20);
  first20.forEach(([num, r2]) => {
    const r3 = rank3.get(num) ?? "?";
    const r4 = rank4.get(num) ?? "?";
    const d32 = typeof r3==="number" ? r3-r2 : "?";
    const d43 = typeof r4==="number" && typeof r3==="number" ? r4-r3 : "?";
    console.log(
      `  ${num}   | ${String(r2).padEnd(7)} | ${String(r3).padEnd(7)} | ` +
      `${String(r4).padEnd(7)} | ${String(d32).padEnd(5)} | ${d43}`
    );
  });
}

