// PART G — COMPLEMENT ANALYSIS (N and 9999-N)
// ═══════════════════════════════════════════════════════════════
function testComplementAnalysis(trainCycles) {
  const prizeMap = buildPrizeMap(trainCycles);

  // For each number N, compare with 9999-N
  let samePrize=0, sameDayCount=0, totalPairs=0;
  const samePrizeExamples = [];

  for (const cycle of trainCycles) {
    // Build number → firstDay map
    const firstDayMap = new Map();
    for (const dayEntry of cycle.drawEntries) {
      for (const { number, isNew } of dayEntry.numbers) {
        if (isNew && !firstDayMap.has(number)) {
          firstDayMap.set(number, dayEntry.dayIndexInCycle);
        }
      }
    }

    // Check pairs
    for (const [num, firstDay] of firstDayMap) {
      const v     = numVal(num);
      if (v > 4999) continue; // only check lower half to avoid double-counting
      const comp  = String(9999-v).padStart(4,"0");
      const compDay = firstDayMap.get(comp);
      if (!compDay) continue;

      totalPairs++;

      // Same first day?
      if (firstDay === compDay) sameDayCount++;

      // Same prize?
      const numPrize  = prizeMap.get(num);
      const compPrize = prizeMap.get(comp);
      if (numPrize && compPrize) {
        const np = numPrize[0];
        const cp = compPrize[0];
        if (np === cp) {
          samePrize++;
          if (samePrizeExamples.length < 10) {
            samePrizeExamples.push({ num, comp, prize: np });
          }
        }
      }
    }
  }

  const sameDayRate  = totalPairs>0 ? (sameDayCount/totalPairs*100).toFixed(2) : 0;
  const samePrizeRate= totalPairs>0 ? (samePrize/totalPairs*100).toFixed(2) : 0;
  const expectedSameDay = (1/350*100).toFixed(2); // ~1/cycleLen

  console.log(`\n  Complement analysis (N and 9999-N):`);
  console.log(`  Total pairs checked: ${totalPairs.toLocaleString()}`);
  console.log(`  Same first-day rate: ${sameDayRate}% (expected ~${expectedSameDay}%)`);
  console.log(`  Same prize rate: ${samePrizeRate}%`);
  console.log(`  Same-prize examples: ${samePrizeExamples.map((e)=>`${e.num}+${e.comp}=₹${e.prize}`).join(", ")}`);
  console.log(`  → ${parseFloat(sameDayRate) > parseFloat(expectedSameDay)*2 ? "✅ SIGNAL: complements appear same day!" : "❌ random"}`);

  // Also test N + (5000-N) mod 10000
  console.log(`\n  Testing N and (5000-N)%10000 pairing...`);
}

