// PART D — WITHIN-DAY COMMON PROPERTY
// ═══════════════════════════════════════════════════════════════
function testWithinDayCommonProperty(trainCycles) {
  const tests = [];

  for (const cycle of trainCycles) {
    for (const dayEntry of cycle.drawEntries.slice(0,50)) {
      const newNums = dayEntry.numbers
        .filter((n)=>n.isNew)
        .map((n)=>n.number);
      if (newNums.length < 10) continue;

      // Test: all have same digit sum mod K?
      for (const K of [2,3,4,5,6,7,8,9,10]) {
        const mods = new Set(newNums.map((n) => digitSum(n) % K));
        if (mods.size === 1) {
          tests.push({ type:`digitSum%${K}`, value:[...mods][0], cycle:cycle.cycleNumber, day:dayEntry.dayIndexInCycle, n:newNums.length });
        }
      }

      // Test: all have same value mod K?
      for (const K of [2,3,4,5,7,10,11,13]) {
        const mods = new Set(newNums.map((n) => numVal(n) % K));
        if (mods.size === 1) {
          tests.push({ type:`val%${K}`, value:[...mods][0], cycle:cycle.cycleNumber, day:dayEntry.dayIndexInCycle, n:newNums.length });
        }
      }

      // Test: all first digits same?
      const firstDigits = new Set(newNums.map((n)=>n[0]));
      if (firstDigits.size === 1) {
        tests.push({ type:"firstDigit", value:[...firstDigits][0], cycle:cycle.cycleNumber, day:dayEntry.dayIndexInCycle, n:newNums.length });
      }

      // Test: all last digits same?
      const lastDigits = new Set(newNums.map((n)=>n[3]));
      if (lastDigits.size === 1) {
        tests.push({ type:"lastDigit", value:[...lastDigits][0], cycle:cycle.cycleNumber, day:dayEntry.dayIndexInCycle, n:newNums.length });
      }
    }
  }

  if (tests.length === 0) {
    console.log(`\n  No days found where ALL new numbers share a common property.`);
    console.log(`  → No within-day formula exists.`);
  } else {
    console.log(`\n  Found ${tests.length} cases where all new numbers share a property:`);
    tests.slice(0,20).forEach((t) => {
      console.log(`    Cycle ${t.cycle} Day ${t.day}: all ${t.n} new nums have ${t.type}=${t.value}`);
    });
  }

  // Weaker test: what % of each day shares a common property?
  console.log(`\n  Partial property sharing (what % of day's new numbers share same digitSum%K):`);
  const shareRates = {};
  for (const K of [3,7,10]) {
    let totalShare=0, totalDays=0;
    for (const cycle of trainCycles) {
      for (const dayEntry of cycle.drawEntries) {
        const newNums = dayEntry.numbers.filter((n)=>n.isNew).map((n)=>n.number);
        if (newNums.length < 5) continue;
        const modCounts = {};
        newNums.forEach((n) => { const m=digitSum(n)%K; modCounts[m]=(modCounts[m]||0)+1; });
        const maxShare = Math.max(...Object.values(modCounts));
        totalShare += maxShare/newNums.length;
        totalDays++;
      }
    }
    const avgShare = totalShare/totalDays;
    shareRates[K] = avgShare;
    const expectedRandom = 1/K;
    console.log(`    digitSum%${K}: avg max share = ${(avgShare*100).toFixed(1)}% (random expected: ${(expectedRandom*100).toFixed(1)}%)`);
  }
}

