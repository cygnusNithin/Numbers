const numVal   = (s) => parseInt(s, 10);
const digitSum = (s) => s.split("").reduce((a,d) => a+Number(d), 0);
const digitProd= (s) => s.split("").reduce((a,d) => a*(Number(d)||1), 1);
const mean     = (arr) => arr.length ? arr.reduce((a,b)=>a+b,0)/arr.length : 0;
const stdDev   = (arr) => {
  if (arr.length<2) return 0;
  const m = mean(arr);
  return Math.sqrt(arr.reduce((s,v)=>s+(v-m)**2,0)/arr.length);
};

// Build number → prizes map across all training cycles
function buildPrizeMap(trainCycles) {
  const map = new Map(); // number → [prizes across cycles]
  for (const cycle of trainCycles) {
    for (const dayEntry of cycle.drawEntries) {
      for (const { number, prize, isNew } of dayEntry.numbers) {
        if (!isNew) continue;
        if (!map.has(number)) map.set(number, []);
        map.get(number).push(prize);
      }
    }
  }
  return map;
}

// Build cycle → [ {day, number, prize} ] sorted by day
function buildCycleSequence(cycle) {
  const seq = [];
  for (const dayEntry of cycle.drawEntries) {
    for (const { number, prize, isNew } of dayEntry.numbers) {
      if (!isNew) continue;
      seq.push({ day: dayEntry.dayIndexInCycle, number, prize, val: numVal(number) });
    }
  }
  return seq.sort((a,b) => a.day - b.day || a.val - b.val);
}

