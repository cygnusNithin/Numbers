// PART B — DAY-TO-DAY TRANSFORMATION
// ═══════════════════════════════════════════════════════════════
function testDayToDayTransformation(trainCycles) {
  const cycle = trainCycles.find((c) => c.cycleNumber === 2);
  if (!cycle) return;

  const entries = cycle.drawEntries.slice(0, 20);

  // For each consecutive pair of days, check various transforms
  console.log(`\n  Testing transforms between consecutive days (cycle 2):\n`);

  let bestTransform = { name: "none", matchRate: 0 };

  for (let i = 0; i < Math.min(entries.length-1, 10); i++) {
    const todayNums = new Set(entries[i].numbers.filter((n)=>n.isNew).map((n)=>n.number));
    const tomorNums = new Set(entries[i+1].numbers.filter((n)=>n.isNew).map((n)=>n.number));

    if (todayNums.size === 0 || tomorNums.size === 0) continue;

    // Transform 1: N+K (shift by constant)
    for (const K of [1, 10, 100, 1000, 33, 37]) {
      const shifted = new Set([...todayNums].map((n) => String((numVal(n)+K) % 10000).padStart(4,"0")));
      const overlap = [...shifted].filter((n) => tomorNums.has(n)).length;
      const rate    = overlap / tomorNums.size;
      if (rate > 0.1) {
        console.log(`    Day ${i+1}→${i+2}: shift+${K} matches ${overlap}/${tomorNums.size} (${(rate*100).toFixed(1)}%)`);
        if (rate > bestTransform.matchRate) bestTransform = { name: `shift+${K}`, matchRate: rate };
      }
    }

    // Transform 2: Complement (9999-N)
    const compl = new Set([...todayNums].map((n) => String(9999-numVal(n)).padStart(4,"0")));
    const complOverlap = [...compl].filter((n) => tomorNums.has(n)).length;
    if (complOverlap > 5) {
      console.log(`    Day ${i+1}→${i+2}: complement matches ${complOverlap}/${tomorNums.size} (${(complOverlap/tomorNums.size*100).toFixed(1)}%)`);
    }

    // Transform 3: 10000-N
    const inv = new Set([...todayNums].map((n) => String((10000-numVal(n))%10000).padStart(4,"0")));
    const invOverlap = [...inv].filter((n) => tomorNums.has(n)).length;
    if (invOverlap > 5) {
      console.log(`    Day ${i+1}→${i+2}: inverse(10000-N) matches ${invOverlap}/${tomorNums.size}`);
    }

    // Transform 4: digit reversal
    const rev = new Set([...todayNums].map((n) => n.split("").reverse().join("")));
    const revOverlap = [...rev].filter((n) => tomorNums.has(n)).length;
    if (revOverlap > 5) {
      console.log(`    Day ${i+1}→${i+2}: digit-reverse matches ${revOverlap}/${tomorNums.size}`);
    }

    // Transform 5: rotate digits
    const rot1 = new Set([...todayNums].map((n) => n[1]+n[2]+n[3]+n[0]));
    const rot1Overlap = [...rot1].filter((n) => tomorNums.has(n)).length;
    if (rot1Overlap > 5) {
      console.log(`    Day ${i+1}→${i+2}: rotate-left matches ${rot1Overlap}/${tomorNums.size}`);
    }

    // Raw overlap (same numbers appear tomorrow)
    const rawOverlap = [...todayNums].filter((n) => tomorNums.has(n)).length;
    const expectedOverlap = (todayNums.size * tomorNums.size) / 10000;
    if (rawOverlap > expectedOverlap * 1.5) {
      console.log(`    Day ${i+1}→${i+2}: RAW overlap=${rawOverlap} vs expected=${expectedOverlap.toFixed(1)} (${(rawOverlap/expectedOverlap).toFixed(2)}x)`);
    }
  }

  // Overall same-number consecutive day overlap
  let totalOverlap=0, totalExpected=0, totalDays=0;
  for (const cycle of trainCycles) {
    for (let i=0; i<cycle.drawEntries.length-1; i++) {
      const a = new Set(cycle.drawEntries[i].numbers.filter((n)=>n.isNew).map((n)=>n.number));
      const b = new Set(cycle.drawEntries[i+1].numbers.filter((n)=>n.isNew).map((n)=>n.number));
      if (a.size<5 || b.size<5) continue;
      const ov = [...a].filter((n)=>b.has(n)).length;
      totalOverlap += ov;
      totalExpected += (a.size*b.size)/10000;
      totalDays++;
    }
  }
  const overlapRatio = totalOverlap/totalExpected;
  console.log(`\n  Overall consecutive-day overlap ratio: ${overlapRatio.toFixed(3)}x expected`);
  console.log(`  (1.0=random, >2.0=structural)  → ${overlapRatio > 1.3 ? "✅ SIGNAL" : "❌ random"}`);
  console.log(`  Best transform found: ${bestTransform.name} (${(bestTransform.matchRate*100).toFixed(1)}%)`);
}

