def parse_row_to_list(s):
    parts = [p.strip() for p in s.split(",")]
    vals = [None if (p.lower() == "nan" or p == "") else p for p in parts]
    return vals

grid = [parse_row_to_list(s) for s in rows_text]
max_cols = max(len(r) for r in grid)
for r in grid:
    while len(r) < max_cols:
        r.append(None)

col_names = [f"RS{i}" for i in range(1, max_cols + 1)]
grid_df = pd.DataFrame(grid, columns=col_names)

# -----------------------------
# Helpers
# -----------------------------
def safe_digit(s, idx):
    if s is None or len(s) != 4 or not s.isdigit():
        return None
    return int(s[idx])

def forward_gap(seq, prev_digit, curr_digit):
    if prev_digit is None or curr_digit is None or seq is None:
        return None
    try:
        prev_idx = seq.index(prev_digit)
        curr_idx = seq.index(curr_digit)
    except ValueError:
        return None
    n = len(seq)
    return (curr_idx - prev_idx) % n

# -----------------------------
# Gap logging into wide format
# -----------------------------
rows_out = []
for roll_idx in range(1, len(grid_df)):  # start at second row
    prev_row = grid_df.iloc[roll_idx - 1]
    curr_row = grid_df.iloc[roll_idx]

    row_dict = {}
    for rs_id in range(1, 19):  # 18 rollersets
        prev_val = prev_row.get(f"RS{rs_id}", None)
        curr_val = curr_row.get(f"RS{rs_id}", None)
        if prev_val is None or curr_val is None:
            row_dict[f"rollerset{rs_id}gap"] = "nan"
            continue

        gaps = []
        for d in range(4):  # thousands,hundreds,tens,ones
            prev_d = safe_digit(prev_val, d)
            curr_d = safe_digit(curr_val, d)
            seq = seq_map.get(rs_id, None)
            g = forward_gap(seq, prev_d, curr_d)
            gaps.append(g)

        row_dict[f"rollerset{rs_id}gap"] = str(gaps)

    rows_out.append(row_dict)

# -----------------------------
